#: words a text must not use for the event's state (R-notifications-02, "never overstates")
OVERSTATED: dict[str, tuple[str, ...]] = {
    "swap_requested": ("accepted", "approved"),
    "swap_accepted": ("approved", "refused"),
    "swap_declined": ("approved",),
    "swap_refused": ("approved",),
}


def _has_word(text: str, word: str, flags: int = 0) -> bool:
    """`word` in `text`, not as part of a longer word ("Mo" is not in "Monday", "Sam" not in "Same")."""
    return re.search(rf"(?<![A-Za-z]){re.escape(word)}(?![A-Za-z])", text, flags) is not None


def _carries(text: str, value: str) -> bool:
    """A date or a start is a substring; a name, a role or a reason code is a whole word, verbatim."""
    return value in text if value[:1].isdigit() else _has_word(text, value)


def _ids_of(event: ports.Event) -> list[int]:
    single = ("request_id", "member_id", "recipient_id")
    ids = [getattr(event, name) for name in single if hasattr(event, name)]
    return ids + list(getattr(event, "recipient_ids", ()))


def _text_findings(text: str, event: ports.Event, carried: tuple[str, ...]) -> list[str]:
    """Everything wrong with `text` as the text of `event`; the empty list when nothing is."""
    findings = [f"does not carry {value!r}" for value in carried if not _carries(text, value)]
    state = _code(event).rsplit("_", 1)[1]
    if not _has_word(text, state, re.IGNORECASE):
        findings.append(f"does not name the state {state!r}")
    findings += [f"overstates with {w!r}" for w in OVERSTATED.get(_code(event), ()) if w in text.lower()]
    findings += [f"shows the id {i}" for i in _ids_of(event) if str(i) in text]
    names = [n for seat in (*TEAM, NEWCOMER) for n in (seat.row_name, seat.directory_name)]
    findings += [f"names {n!r}, which is not in the payload" for n in names if _has_word(text, n)]
    return findings


