def test_arm3_list_is_the_callers_own_newest_first_by_created_at_then_id_desc(world: World) -> None:
    """A's four rows: a at NOW, b and c at NOW+1h (c the higher id), d at NOW-4h with the highest id, so
    created_at order and id order disagree; B's rows are interleaved. A sees [c, b, a, d], B sees its own."""
    _notify(world, ports.MemberAdded(member_id=A, role="planner"))  # a
    _notify(world, ports.MemberAdded(member_id=B, role="planner"))
    world.clock.advance(hours=1)
    _notify(world, ports.RoleChanged(member_id=A, role="planner"))  # b
    _notify(world, ports.RoleChanged(member_id=B, role="planner"))
    _notify(world, _published(A))  # c: the same instant as b, a higher id
    world.clock.advance(hours=-5)
    _notify(world, _requested(A))  # d: the oldest instant, the highest id of A's
    _notify(world, _requested(B))
    rows = {(r.recipient_id, r.event): r for r in _rows(world.engine)}
