def _refusal(world: World, call: Call) -> Refused:
    """The refusal, with pytest.raises around the unit of work. It also asserts the refusal changed nothing:
    the swaps tables through the caller's session as the refusal propagates and again on their own, nothing
    emitted, no transfer attempted."""
    before, sent, attempts = _stored(world.engine), list(world.spy.sent), list(world.scheduling.attempts)
    inside: list[Stored] = []
    with pytest.raises(Refused) as refused:
        with db.unit_of_work(world.engine) as session:
            try:
                call(world.service)
            except Refused:
                inside.append(_read(session))
                raise
    assert inside == [before], "a write was made in the caller's session before the refusal"
    assert _stored(world.engine) == before
    assert world.spy.sent == sent
    assert world.scheduling.attempts == attempts
    return refused.value


def _set_clock(clock: FixedClock, at: datetime) -> None:
    clock.advance(seconds=int((at - clock.now()).total_seconds()))


