def _decided_row(req: Req, decision: tuple, state: str) -> RequestRow:
    """The expected answer of a decide: the stored request with the decision embedded, the state and display
    state the outcome, awaiting none, party False (Q-22 (a): the decider is never a party). `decision` is the
    stored decisions row read back, so its id is the store's."""
    slot = SLOT[req.assignment_id]
    decision_id, request_id, decider_id, outcome, reason, decided_at = decision
    return RequestRow(
        id=req.id,
        assignment_id=req.assignment_id,
        shift_date=slot.day,
        shift_start=time.fromisoformat(slot.start),
        requester_id=req.requester_id,
        requester_name=NAME[req.requester_id],
        counterpart_id=req.counterpart_id,
        counterpart_name=NAME[req.counterpart_id],
        reason=req.reason,
        state=state,
        display_state=state,
        awaiting="none",
        created_at=req.created_at,
        answered_at=req.answered_at,
        answer_reason=req.answer_reason,
        decision=DecisionValue(
            id=decision_id,
            request_id=request_id,
            decider_id=decider_id,
            outcome=outcome,
            reason=reason,
            decided_at=decided_at,
        ),
        party=False,
    )


def _event_fields(event: object) -> tuple:
    """An outcome event without its recipients, whose order is not pinned."""
    last = event.new_holder_name if isinstance(event, ports.SwapApproved) else event.reason
    return (type(event), event.request_id, event.shift_date, event.shift_start, last)


