class Case(NamedTuple):
    arrange: Arrange
    call: Call
    reason: str


def _requests(*requests: Req) -> Arrange:
    def arrange(world: World) -> None:
        _put(world.engine, *requests)

    return arrange


def _past_deadline(*requests: Req) -> Arrange:
    def arrange(world: World) -> None:
        _put(world.engine, *requests)
        _set_clock(world.clock, _deadline(A1))

    return arrange


def _accepted_in(state: str) -> Req:
    """ACCEPTED, stored in another state (with its decision when one exists)."""
    if state == "requested":
        return ACCEPTED._replace(state=state, answered_at=None)
    if state == "declined":
        return ACCEPTED._replace(state=state, answer_reason="unavailable")
    reason = None if state == "approved" else "fairness"
    return ACCEPTED._replace(state=state, decision=Dec(961, AVI, state, reason, T(11, 11)))


