# ==================================================================================================== arm 10
def _intersects(a: dict, b: dict) -> bool:
    return a["date"] == b["date"] and not (a["end"] <= b["start"] or a["start"] >= b["end"])


def _section6_parties(fixture: dict) -> tuple[dict, int, int, int]:
    """From the fixture's data: an assignment with no request, held by a member-role member; a member-role
    counterpart eligible by R-swaps-08 (not the requester, no slot on that shift, no intersecting shift that
    date); a planner, who is no party since both parties are members. The first such choice in id order."""
    members = {m["id"]: m for m in fixture["members"]}
    shift_of = {s["id"]: s for s in fixture["shifts"]}
    requested = {r["assignment_id"] for r in fixture["swap_requests"]}
    planner = min(m["id"] for m in fixture["members"] if m["role"] == "planner")
    for a in fixture["assignments"]:
        if a["id"] in requested or members[a["member_id"]]["role"] != "member":
            continue
        shift = shift_of[a["shift_id"]]
        for m in fixture["members"]:
            if m["role"] != "member" or not m["active"] or m["id"] == a["member_id"]:
                continue
            held = [shift_of[o["shift_id"]] for o in fixture["assignments"] if o["member_id"] == m["id"]]
            if any(h["id"] == shift["id"] or _intersects(h, shift) for h in held):
                continue
            return a, a["member_id"], m["id"], planner
    raise AssertionError("the fixture holds no such assignment and counterpart")


def test_arm10_request_accept_approve_through_the_real_services_notifies_exactly_and_moves_the_holder(
    tmp_path: Path,
) -> None:
    """The brief's section 6 path (M2's usable path), from seeded_week(20261107) under a FixedClock: a member
    requests, the counterpart accepts, a non-party planner approves. Identity, scheduling, swaps and
    notifications are the composition root's real services; every caller is resolved by identity from the
    fixture's token. The whole notifications table is exactly R-notifications-01's, and the real board shows
    the counterpart as the holder with nothing pending."""
    fixture = synthetic.seeded_week(SEED)
    clock = FixedClock(synthetic.CLOCK)
    app = create_app(workspace=tmp_path, clock=clock)
    engine = db.engine_for(tmp_path)
    synthetic.load_fixture(engine, fixture)

    assignment, requester, counterpart, planner = _section6_parties(fixture)
    members = {m["id"]: m for m in fixture["members"]}
    shift = next(s for s in fixture["shifts"] if s["id"] == assignment["shift_id"])
    # sanity: the choice is what the arm needs, and the path runs well before the deadline
    assert assignment["id"] not in {r["assignment_id"] for r in fixture["swap_requests"]}
    assert (members[requester]["role"], members[counterpart]["role"], members[planner]["role"]) == (
        "member",
        "member",
        "planner",
    )
    assert counterpart != requester
    start_at = datetime.combine(date.fromisoformat(shift["date"]), time.fromisoformat(shift["start"]))
    assert synthetic.CLOCK + timedelta(hours=2) < start_at - DAY24

    def caller(member_id: int) -> ports.Caller:
        with db.unit_of_work(engine):
            resolved = app.state.ports.member_directory.caller_for_token(members[member_id]["token"])
        assert resolved is not None and resolved.member_id == member_id
        return resolved

    swaps = app.state.ports.swaps
    with db.unit_of_work(engine):
        requested = swaps.request(caller(requester), assignment["id"], counterpart, "family")
    clock.advance(minutes=30)
    with db.unit_of_work(engine):
        swaps.answer(caller(counterpart), requested.id, "accept")
    clock.advance(minutes=30)
    with db.unit_of_work(engine):
        decided = swaps.decide(caller(planner), requested.id, "approve")

    assert (decided.id, decided.state, decided.display_state, decided.awaiting) == (
        requested.id,
        "approved",
        "approved",
        "none",
    )
    assert (decided.decision.outcome, decided.decision.decider_id, decided.decision.request_id) == (
        "approved",
        planner,
        requested.id,
    )
    assert decided.decision.decided_at == synthetic.CLOCK + timedelta(hours=1)

    deciders = {m["id"] for m in fixture["members"] if m["active"] and m["role"] in ("admin", "planner")}
    assert deciders and not deciders & {requester, counterpart}
    with db.unit_of_work(engine) as session:
        table = Counter((n.recipient_id, n.event) for n in session.scalars(select(models.Notification)))
    assert table == Counter(
        [
            (counterpart, "swap_requested"),
            (requester, "swap_accepted"),
            *[(d, "swap_accepted") for d in deciders],
            (requester, "swap_approved"),
            (counterpart, "swap_approved"),
        ]
    )

    viewer = caller(planner)
    with db.unit_of_work(engine):
        board = app.state.ports.scheduling.board(viewer, synthetic.WEEK_START)
    (holder,) = [h for s in board.shifts for h in s.holders if h.assignment_id == assignment["id"]]
    assert (holder.member_id, holder.name, holder.pending) == (
        counterpart,
        members[counterpart]["name"],
        None,
    )
