def test_arm8_the_board_over_seeded_week_has_21_shifts_42_rows_5_pending_and_the_admins_requestable(
    tmp_path: Path,
) -> None:
    """The timing arm's deterministic sibling: the board over seeded_week(20261107) (R-scheduling-09), as the
    fixture's admin, mine unset.

    FakeSwapsPort is configured from the fixture. Each open request's state is its row's pending. requestable
    is set True on the admin's own assignments that have no open request, which is what swaps would answer by
    R-swaps-01/02/06. That configuration is an ECHO of the double, not an oracle. The oracles:
    - 21 shifts and 42 holder-rows;
    - 5 rows pending (3 requested, 2 accepted), and they are the rows of the five requested assignments;
    - every requestable row's member_id, taken from scheduling's rows, is the admin's, and the requestable
      rows are exactly the admin's assignments on the board minus those with an open request;
    - the one swaps call carries the admin's id, week_published True, and the 42 triples whose holder ids and
      start instants are the fixture's.
    """
    fixture = synthetic.seeded_week(SEED)
    engine = db.engine_for(tmp_path)
    synthetic.load_fixture(engine, fixture)
    (admin,) = [m for m in fixture["members"] if m["role"] == "admin"]
    directory = FakeMemberDirectory()
    for m in fixture["members"]:
        directory.add(m["id"], m["name"], m["role"], active=m["active"])
    open_ids = {
        r["assignment_id"] for r in fixture["swap_requests"] if r["state"] in ("requested", "accepted")
    }
    swaps = FakeSwapsPort()
    for r in fixture["swap_requests"]:  # ECHO: the double answers what it is told
        swaps.set_view(r["assignment_id"], AssignmentView(pending=r["state"], requestable=False))
    for a in fixture["assignments"]:  # ECHO
        if a["member_id"] == admin["id"] and a["id"] not in open_ids:
            swaps.set_view(a["id"], AssignmentView(pending=None, requestable=True))
    clock = FixedClock(datetime.fromisoformat(fixture["clock"]))
    service = SchedulingService(
        lambda: SimpleNamespace(clock=clock, member_directory=directory, swaps=swaps, notifier=SpyNotifier())
    )
    caller = ports.Caller(member_id=admin["id"], name=admin["name"], role=admin["role"], active=True)
    with db.unit_of_work(engine):
        board = service.board(caller, date.fromisoformat(fixture["weeks"][0]["start_date"]))

    holders = [h for s in board.shifts for h in s.holders]
    assert len(board.shifts) == 21
    assert len(holders) == 42
    assert Counter(h.pending for h in holders if h.pending is not None) == Counter(requested=3, accepted=2)
    assert {h.assignment_id for h in holders if h.pending is not None} == open_ids

    admins_rows = {h.assignment_id for h in holders if h.member_id == admin["id"]}  # scheduling's rows
    assert admins_rows == {a["id"] for a in fixture["assignments"] if a["member_id"] == admin["id"]}
    requestable = [h for h in holders if h.requestable]
    assert requestable and {h.member_id for h in requestable} == {admin["id"]}
    assert {h.assignment_id for h in requestable} == admins_rows - open_ids

    shift_of = {s["id"]: s for s in fixture["shifts"]}
    triples = sorted(
        (
            a["id"],
            a["member_id"],
            _start_at(date.fromisoformat(shift_of[a["shift_id"]]["date"]), shift_of[a["shift_id"]]["start"]),
        )
        for a in fixture["assignments"]
    )
    ((caller_id, published, rows),) = swaps.calls
    assert (caller_id, published) == (admin["id"], True)
    assert sorted(rows) == triples
