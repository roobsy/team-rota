from pathlib import Path

from sqlalchemy import Engine

from app import models
from app.db import session_for

SYNTHETIC = (
    "This fixture is synthetic: generated by src/app/synthetic.py seeded_week(seed) for Team Rota; "
    "no real person, no real data."
)
FIXTURE_NAMES = (
    "Ada",
    "Bea",
    "Cal",
    "Dee",
    "Eli",
    "Fay",
    "Gus",
    "Hal",
    "Ida",
    "Jem",
    "Kit",
    "Lou",
    "Max",
    "Nia",
    "Obi",
    "Pim",
    "Quy",
    "Rae",
    "Sol",
    "Tam",
    "Uma",
    "Vic",
    "Wyn",
    "Xan",
    "Yas",
    "Zed",
)
CLOCK = datetime(2026, 11, 5, 9, 0, 0)
WEEK_START = date(2026, 11, 9)
SHIFT_TIMES = ((time(8), time(12)), (time(12), time(16)), (time(16), time(20)))
SLOTS = 2
ROLES_BY_ID = {1: "admin", 2: "planner", 3: "planner"}
REQUEST_STATES = ("requested", "accepted", "requested", "accepted", "requested")
DEADLINE = timedelta(hours=24)
DEFAULT_SEED = 20261107
FIXTURE_DIR = Path(__file__).resolve().parents[2] / "tests" / "fixtures"


def _iso_min(t: time) -> str:
    return t.isoformat("minutes")


def seeded_week(seed: int) -> dict:
    rng = random.Random(seed)
    names = rng.sample(FIXTURE_NAMES, 12)
    members = []
    for i, name in enumerate(names, start=1):
        passcode = f"{name.lower()}-{rng.randrange(1000, 9999)}"
        salt = f"{rng.randrange(16**8):08x}"
        members.append(
            {
                "id": i,
                "name": name,
                "email": f"{name.lower()}{i}@example.test",
                "role": ROLES_BY_ID.get(i, "member"),
                "active": True,
                "passcode": passcode,
                "passcode_hash": models.hash_passcode(passcode, salt),
                "token": f"tok_{i}_{rng.randrange(16**6):06x}",
            }
        )
    shifts = []
    for d in range(7):
        day = WEEK_START + timedelta(days=d)
        for start, end in SHIFT_TIMES:
            shifts.append(
                {
                    "id": len(shifts) + 1,
                    "week_start": WEEK_START.isoformat(),
                    "date": day.isoformat(),
                    "start": _iso_min(start),
                    "end": _iso_min(end),
                    "slots": SLOTS,
                }
            )
    assignments = []
    for (
        shift
    ) in shifts:  # slots walked by date, start, slot index; round-robin over all 12 members in id order
        for _slot in range(SLOTS):
            assignments.append(
                {
                    "id": len(assignments) + 1,
                    "shift_id": shift["id"],
                    "member_id": (len(assignments) % 12) + 1,
                }
            )
    shift_of = {s["id"]: s for s in shifts}
    requests = []
    for n, state in enumerate(REQUEST_STATES, start=1):
        a = assignments[n - 1]
        sh = shift_of[a["shift_id"]]
        eligible = []
        for m in (
            members
        ):  # R-swaps-08: active, not the holder, no slot on that shift, no intersecting shift that day
            if m["id"] == a["member_id"]:
                continue
            busy = False
            for other in assignments:
                if other["member_id"] != m["id"]:
                    continue
                osh = shift_of[other["shift_id"]]
                if osh["id"] == sh["id"] or (
                    osh["date"] == sh["date"] and not (osh["end"] <= sh["start"] or osh["start"] >= sh["end"])
                ):
                    busy = True
                    break
            if not busy:
                eligible.append(m["id"])
        counterpart = rng.choice(eligible)
        requests.append(
            {
                "id": n,
                "assignment_id": a["id"],
                "requester_id": a["member_id"],
                "counterpart_id": counterpart,
                "reason": "other",
                "state": state,
                "created_at": CLOCK.isoformat(),
                "answered_at": (CLOCK + timedelta(minutes=30)).isoformat() if state == "accepted" else None,
                "answer_reason": None,
            }
        )
    return {
        "SYNTHETIC": SYNTHETIC,
        "seed": seed,
        "rule": "R-scheduling-09",
        "clock": CLOCK.isoformat(),
        "admin_token": members[0]["token"],
        "members": members,
        "weeks": [{"start_date": WEEK_START.isoformat(), "state": "published"}],
        "shifts": shifts,
        "assignments": assignments,
        "swap_requests": requests,
    }


def serialise(fixture: dict) -> bytes:
    return (json.dumps(fixture, indent=1, ensure_ascii=True, allow_nan=False) + "\n").encode("ascii")


def load_fixture(engine: Engine, fixture: dict) -> None:
    """Inserts the fixture's rows in id order (ids are creation-ordered; the store assigns the same ids)."""
    with session_for(engine) as s:
        for m in fixture["members"]:
            s.add(
                models.Member(
                    id=m["id"],
                    name=m["name"],
                    email=m["email"],
                    role=m["role"],
                    active=m["active"],
                    passcode_hash=m["passcode_hash"],
                    token=m["token"],
                )
            )
        for w in fixture["weeks"]:
            s.add(models.Week(start_date=date.fromisoformat(w["start_date"]), state=w["state"]))
        s.flush()
        for sh in fixture["shifts"]:
            s.add(
                models.Shift(
                    id=sh["id"],
                    week_start=date.fromisoformat(sh["week_start"]),
                    date=date.fromisoformat(sh["date"]),
                    start=time.fromisoformat(sh["start"]),
                    end=time.fromisoformat(sh["end"]),
                    slots=sh["slots"],
                )
            )
        s.flush()
        for a in fixture["assignments"]:
            s.add(models.Assignment(id=a["id"], shift_id=a["shift_id"], member_id=a["member_id"]))
        s.flush()
        for r in fixture["swap_requests"]:
            s.add(
                models.SwapRequest(
                    id=r["id"],
                    assignment_id=r["assignment_id"],
                    requester_id=r["requester_id"],
                    counterpart_id=r["counterpart_id"],
                    reason=r["reason"],
                    state=r["state"],
                    created_at=datetime.fromisoformat(r["created_at"]),
                    answered_at=datetime.fromisoformat(r["answered_at"]) if r["answered_at"] else None,
                    answer_reason=r["answer_reason"],
                )
            )
        s.commit()


def write_fixture(seed: int = DEFAULT_SEED, out: Path | None = None) -> Path:
    target = out or FIXTURE_DIR / f"seeded_week_{seed}.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(serialise(seeded_week(seed)))
    return target


if __name__ == "__main__":  # the regeneration command: uv run python -m app.synthetic [seed]
    print(write_fixture(int(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SEED))
