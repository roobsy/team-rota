"""The seeded fixture of R-scheduling-09, reproducible byte for byte for one seed (hard rule 3: SYNTHETIC).

seeded_week(seed) builds the fixture as plain data; serialise() gives its canonical bytes; load_fixture()
inserts it into a database; write_fixture() is the regeneration command (`uv run python -m app.synthetic`).
The seeded generator draws only what the rule lets it vary: names, emails, passcodes and the counterparts.
Everything else is fixed by the rule.
"""

